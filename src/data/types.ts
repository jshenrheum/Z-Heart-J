import type { DateStr } from '../lib/dates.ts';
import type { Recurrence } from '../lib/recurrence.ts';

export type MemberId = 'jeffrey' | 'zul';
export type Assignee = MemberId | 'both';

export const MEMBERS: Record<MemberId, { id: MemberId; name: string; initial: string }> = {
  jeffrey: { id: 'jeffrey', name: 'Jeffrey', initial: 'J' },
  zul: { id: 'zul', name: 'Zul', initial: 'Z' },
};
export const MEMBER_IDS: MemberId[] = ['jeffrey', 'zul'];
export const otherMember = (m: MemberId): MemberId => (m === 'jeffrey' ? 'zul' : 'jeffrey');

export type FieldKind = 'text' | 'phone' | 'fax' | 'address' | 'email' | 'url' | 'identifier' | 'date';

/** Who changed a record, and when. Attribution only — never a privacy control. */
export interface Audit {
  updatedBy: MemberId;
  /** ISO timestamp (UTC). */
  updatedAt: string;
  /** Server-assigned; a write must name the version it started from (409 otherwise). */
  version: number;
}

export interface Profile extends Audit {
  id: MemberId;
  displayName: string;
  specialty: string;
  organization: string;
  /** NPI is a text identifier: all digits preserved. Public professional identifier. */
  npi: string;
}

export interface WorkLocation extends Audit {
  id: string;
  owner: MemberId;
  label: string;
  organization: string;
  address: string;
  mainPhone: string;
  directPhone: string;
  fax: string;
  schedulingPhone: string;
  notes: string;
}

/**
 * Credentials carry metadata only on the client. The number itself is a protected
 * value that lives encrypted on the server (Stage 2) and is never part of this type.
 */
export interface Credential extends Audit {
  id: string;
  owner: MemberId;
  type: string;
  issuer: string;
  expires?: DateStr;
  renewalUrl?: string;
  /** Presence only — whether a protected value has been saved. */
  hasValue: boolean;
}

export type HomeTemplate = 'address' | 'utility' | 'internet' | 'maintenance' | 'vehicle' | 'pet' | 'emergency' | 'other';

export const HOME_TEMPLATE_LABEL: Record<HomeTemplate, string> = {
  address: 'Address',
  utility: 'Utilities',
  internet: 'Internet',
  maintenance: 'Maintenance',
  vehicle: 'Vehicle',
  pet: 'Pet',
  emergency: 'Emergency',
  other: 'Other',
};

export interface HomeField {
  /** Stable within its record; a protected value is stored under it. */
  id: string;
  label: string;
  kind: FieldKind;
  /** Absent for protected fields: the client only ever sees that one exists. */
  value?: string;
  protected?: boolean;
  /** Protected fields only: whether an encrypted value has been saved. */
  hasValue?: boolean;
}

export interface HomeRecord extends Audit {
  id: string;
  template: HomeTemplate;
  title: string;
  fields: HomeField[];
  notes: string;
}

export interface Contact extends Audit {
  id: string;
  name: string;
  role: string;
  category: string;
  phone: string;
  fax: string;
  email: string;
  address: string;
  website: string;
  note: string;
  aliases: string[];
}

export interface ListItem extends Audit {
  id: string;
  name: string;
  qty: string;
  note: string;
  checked: boolean;
  /** Sort key within the list (fractional, so a move rewrites one item). */
  position: number;
  /** Transient UI state while a change is in flight. */
  sync?: 'saving';
}

export interface SharedList extends Audit {
  id: string;
  title: string;
  description: string;
  items: ListItem[];
}

export interface Plan extends Audit {
  id: string;
  title: string;
  description: string;
  target?: DateStr;
  template: 'travel' | 'wedding' | 'home' | 'custom';
  status: 'active' | 'done';
}

export interface Task extends Audit {
  id: string;
  /** Instances created by recurrence share a seriesId; (seriesId, due) is unique. */
  seriesId: string;
  planId?: string;
  title: string;
  assignee: Assignee;
  due?: DateStr;
  status: 'open' | 'done';
  completedOn?: DateStr;
  recurrence?: Recurrence;
  /** Set on an instance that was generated by completing another one; used so Undo can take it back. */
  createdFrom?: string;
  notes: string;
}

/** A calendar event. Times are wall-clock "HH:MM" in the household's time zone. */
export interface CalendarEvent extends Audit {
  id: string;
  title: string;
  /** Whose it is: one of you, or both. */
  whose: Assignee;
  /** The (first) day. */
  date: DateStr;
  /** All-day events only: the last day of an event spanning several days. */
  endDate?: DateStr;
  /** Absent for all-day events. */
  startTime?: string;
  endTime?: string;
  location: string;
  notes: string;
  repeat?: EventRepeat;
  /** Days of a repeating event that were removed one at a time. */
  skips: DateStr[];
}

export interface EventRepeat {
  every: number;
  unit: 'day' | 'week' | 'month' | 'year';
  /** Last day a repeat may fall on. */
  until?: DateStr;
}

export type PinTarget = { kind: 'profile' | 'record' | 'list' | 'plan' | 'contact'; id: string };

// ------------------------------------------------------------------ our story

/** A photo kept on the server (never public); `w` × `h` in pixels. */
export interface PhotoRef {
  id: string;
  w: number;
  h: number;
}

/** A moment in Our story: a day worth keeping, with its photos. */
export interface Moment extends Audit {
  id: string;
  title: string;
  date: DateStr;
  place: string;
  story: string;
  photos: PhotoRef[];
}

// ------------------------------------------------------------------ wedding

/** The one wedding record (id "wedding"): the date and the day's details. */
export interface WeddingDetails extends Audit {
  id: 'wedding';
  date?: DateStr;
  /** Ceremony time, "HH:MM". */
  time?: string;
  venue: string;
  address: string;
  /** The overall budget, in dollars. */
  budget?: number;
  /** The day's schedule, one moment per line ("4:00 PM Ceremony"). */
  schedule: string;
  notes: string;
}

export type VendorStatus = 'considering' | 'booked';
export type DepositStatus = 'none' | 'due' | 'paid';

export interface Vendor extends Audit {
  id: string;
  name: string;
  category: string;
  /** The person to ask for. */
  contact: string;
  phone: string;
  email: string;
  website: string;
  status: VendorStatus;
  deposit: DepositStatus;
  depositDue?: DateStr;
  notes: string;
}

export type Rsvp = 'pending' | 'yes' | 'no';

export interface Guest extends Audit {
  id: string;
  name: string;
  /** Whose side they're from. */
  side: Assignee;
  /** People in the party, the guest included. */
  party: number;
  rsvp: Rsvp;
  table: string;
  meal: string;
  notes: string;
}

/** A line of the wedding budget, in dollars. */
export interface BudgetItem extends Audit {
  id: string;
  title: string;
  category: string;
  planned: number;
  paid: number;
  notes: string;
}

export interface Household {
  profiles: Profile[];
  locations: WorkLocation[];
  credentials: Credential[];
  home: HomeRecord[];
  contacts: Contact[];
  lists: SharedList[];
  plans: Plan[];
  tasks: Task[];
  events: CalendarEvent[];
  moments: Moment[];
  wedding?: WeddingDetails;
  vendors: Vendor[];
  guests: Guest[];
  budget: BudgetItem[];
  /** Each member's own Home shortcuts. The signed-in app only receives its own. */
  pins: Record<MemberId, PinTarget[]>;
}
